"""Exercise actual staged blobs without reading local research inputs."""
import importlib
import importlib.util
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))


class SourcePolicyTests(unittest.TestCase):
    def api(self):
        self.assertIsNotNone(importlib.util.find_spec('source_policy'), 'staged-source gate missing')
        return importlib.import_module('source_policy')

    def check(self, name, data, symlink=False):
        api = self.api()
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            subprocess.run(['git', 'init', '-q', tmp], check=True)
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            if symlink:
                path.symlink_to(data.decode())
            else:
                path.write_bytes(data)
            subprocess.run(['git', '-C', tmp, 'add', '--', name], check=True)
            # The index, not the possibly edited working file, is authority.
            if not symlink:
                path.write_bytes(b'harmless working copy\n')
            return api.check_index(root)

    def test_original_and_generated_locations_are_rejected(self):
        for name in ('references/roms/game.txt', 'references/dissasm/game.asm',
                     'assets/generated/tiles.asm', '.legacy/seaquest/source.py', 'outputs/report.json'):
            with self.subTest(name=name):
                self.assertTrue(self.check(name, b'text\n'))

    def test_binary_renamed_as_text_is_rejected_from_index(self):
        self.assertTrue(self.check('docs/readme.txt', b'AB\x00\xff' * 1024))

    def test_cartridge_extension_is_rejected_even_when_text(self):
        self.assertTrue(self.check('src/game.rom', b'pretend text\n'))

    def test_symlink_cannot_smuggle_ignored_input(self):
        self.assertTrue(self.check('src/sprite.asm', b'../references/roms/game.bin', symlink=True))

    def test_generated_disassembly_marker_is_rejected(self):
        self.assertTrue(self.check('src/renamed.asm', b'; Disassembly of original ROM generated by DiStella\n'))

    def test_synthetic_sources_and_compact_hashes_are_allowed(self):
        self.assertEqual(self.check('src/diagnostic.asm', b'org $4000\ndb "AB"\n'), [])
        self.assertEqual(self.check('references/manifest.json', b'{"sha256":"abc"}\n'), [])


class VersionIdentityTests(unittest.TestCase):
    def api(self):
        self.assertIsNotNone(importlib.util.find_spec('ci_verify'), 'CI identity gate missing')
        return importlib.import_module('ci_verify')

    def test_changed_bytes_need_new_baseline_version(self):
        baseline = {'version': '0.0.1', 'rom': {'size': 3, 'sha256':
            'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad'}}
        self.api().check_artifact(b'abc', '0.0.1', baseline)
        with self.assertRaises(ValueError):
            self.api().check_artifact(b'abd', '0.0.1', baseline)
        with self.assertRaises(ValueError):
            self.api().check_artifact(b'abc', '0.0.2', baseline)
